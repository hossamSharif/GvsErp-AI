#!/usr/bin/env tsx
/**
 * Database Types Generation Script
 *
 * Generates TypeScript types from Supabase database schema.
 *
 * Usage:
 *   pnpm --filter @erp/database generate-types
 *
 * Requirements:
 *   - SUPABASE_PROJECT_ID environment variable
 *   - Supabase CLI installed (npx supabase)
 *   - Authenticated with Supabase (npx supabase login)
 */

import { execSync } from 'child_process';
import { writeFileSync, existsSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';

const OUTPUT_PATH = join(__dirname, '../src/types/database.types.ts');

async function generateTypes() {
  const projectId = process.env.SUPABASE_PROJECT_ID;

  if (!projectId) {
    console.error('Error: SUPABASE_PROJECT_ID environment variable is required');
    console.log('\nUsage:');
    console.log('  SUPABASE_PROJECT_ID=your-project-id pnpm generate-types');
    console.log('\nOr set in .env file:');
    console.log('  SUPABASE_PROJECT_ID=your-project-id');
    process.exit(1);
  }

  console.log(`Generating types for project: ${projectId}`);

  try {
    // Ensure output directory exists
    const outputDir = dirname(OUTPUT_PATH);
    if (!existsSync(outputDir)) {
      mkdirSync(outputDir, { recursive: true });
    }

    // Generate types using Supabase CLI
    const command = `npx supabase gen types typescript --project-id ${projectId}`;
    console.log(`Running: ${command}`);

    const output = execSync(command, {
      encoding: 'utf-8',
      maxBuffer: 10 * 1024 * 1024, // 10MB buffer for large schemas
    });

    // Add header comment
    const header = `/**
 * Database Types
 *
 * Auto-generated by Supabase CLI.
 * DO NOT EDIT MANUALLY.
 *
 * Generated: ${new Date().toISOString()}
 * Project: ${projectId}
 *
 * To regenerate:
 *   pnpm --filter @erp/database generate-types
 */

`;

    writeFileSync(OUTPUT_PATH, header + output);
    console.log(`\nTypes generated successfully: ${OUTPUT_PATH}`);
  } catch (error) {
    if (error instanceof Error) {
      console.error('\nError generating types:', error.message);

      if (error.message.includes('not logged in')) {
        console.log('\nPlease login to Supabase first:');
        console.log('  npx supabase login');
      }
    }
    process.exit(1);
  }
}

generateTypes();
