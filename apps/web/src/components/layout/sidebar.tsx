interface SidebarProps {
  isCollapsed: boolean;
  onToggle: () => void;
}

export function Sidebar({ isCollapsed, onToggle }: SidebarProps) {
  const pathname = usePathname();
  const params = useParams();
  const { isRtl } = useDirection();
  const locale = params.locale as string;

  const basePath = `/${locale}`;

  return (
    <aside
      className={cn(
        'h-full bg-card border-e flex flex-col transition-all duration-300',
        isCollapsed ? 'w-16' : 'w-64'
      )}
    >
      {/* Logo */}
      <div className="h-16 flex items-center justify-between px-4 border-b">
        {!isCollapsed && (
          <Link href={basePath} className="flex items-center gap-2">
            <div className="w-8 h-8 rounded-lg bg-primary flex items-center justify-center">
              <span className="text-primary-foreground font-bold text-sm">E</span>
            </div>
            <span className="font-semibold text-lg">ERP SaaS</span>
          </Link>
        )}
        <button
          onClick={onToggle}
          className={cn(
            'p-2 rounded-md hover:bg-muted transition-colors',
            isCollapsed && 'mx-auto'
          )}
          aria-label={isCollapsed ? 'Expand sidebar' : 'Collapse sidebar'}
        >
          {isCollapsed ? (
            <ChevronRightIcon className={cn('w-5 h-5', isRtl && 'rotate-180')} />
          ) : (
            <ChevronLeftIcon className={cn('w-5 h-5', isRtl && 'rotate-180')} />
          )}
        </button>
      </div>

      {/* Navigation */}
      <nav className="flex-1 py-4 overflow-y-auto">
        <ul className="space-y-1 px-2">
          {navItems.map((item) => {
            const href = `${basePath}${item.href}`;
            const matchPath = item.activePrefix
              ? `${basePath}${item.activePrefix}`
              : href;
            const isActive =
              item.href === ''
                ? pathname === basePath || pathname === `${basePath}/`
                : pathname.startsWith(matchPath);

            return (
              <li key={item.href}>
                <Link
                  href={href}
                  className={cn(
                    'flex items-center gap-3 px-3 py-2 rounded-md transition-colors',
                    isActive
                      ? 'bg-primary text-primary-foreground'
                      : 'hover:bg-muted text-foreground',
                    isCollapsed && 'justify-center'
                  )}
                  title={isCollapsed ? item.label : undefined}
                >
                  {item.icon}
                  {!isCollapsed && <span>{item.label}</span>}
                </Link>
              </li>
            );
          })}
        </ul>
      </nav>

      {/* Footer */}
      {!isCollapsed && (
        <div className="p-4 border-t text-xs text-muted-foreground">
          <p>&copy; {new Date().getFullYear()} ERP SaaS</p>
        </div>
      )}
    </aside>
  );
}

